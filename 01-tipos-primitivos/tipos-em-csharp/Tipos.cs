using System;

class Tipos
{
    static void Main()
    {
        int numeroInteiro = 10;
        double numeroDecimal = 10.5;
        char caractere = 'A';
        bool verdadeiro = true;
        string texto = "Olá, mundo!";

        Console.WriteLine("Inteiro: " + numeroInteiro);
        Console.WriteLine("Decimal: " + numeroDecimal);
        Console.WriteLine("Caractere: " + caractere);
        Console.WriteLine("Booleano: " + verdadeiro);
        Console.WriteLine("Texto: " + texto);
    }
}
